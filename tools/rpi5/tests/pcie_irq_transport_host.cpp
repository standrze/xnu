static void fresh(BCM2712PCIePHYTransport &s, bool enabled = true)
{
    s = BCM2712PCIePHYTransport(); s.provider.transport = &s; s.ownerProvider = &s.provider;
    phyOwner = &s; watchdogOwner = nullptr; thread = &thread_id; interruptContext = false;
    daif = enabled ? 0x200 : 0x3c0; /* Debug state must stay unchanged. */
    watchdogClaims = watchdogChecks = failWatchdog = threadReferences = 0;
    gicReads = gicWrites = interruptCalls = resetInits = controllerIO = providerCalls = failProvider = 0;
    failClaim = ignoreGICWrite = providerReenable = providerActive = providerMappingLoss = false;
    providerPhaseLoss = providerCloses = providerReentry = false;
    restoreReenable = false;
    rpi5_pcie_irq_gate = {}; rpi5_pcie_irq_session = {}; rpi5_pcie_irq_thread = nullptr;
    rpi5_pcie_irq_identity = nullptr; rpi5_pcie_irq_mapping = 0; rpi5_pcie_irq_claiming = false;
    std::memset(registers,0,sizeof(registers)); rpi5_gicd_base = (uintptr_t)registers;
    registers[1] = 15; registers[0x114/4] = registers[0x118/4] = registers[0x120/4] = UINT32_MAX;
    registers[0x220/4] = UINT32_MAX; registers[0x320/4] = 0x7f800001;
    s.binding.bridge_regs = {UINT64_C(0x1000120000),UINT64_C(0x1000129310)};
    s.binding.bridge_reset_id = 44; s.binding.gic_phandle = 1;
    s.binding.bridge_intid[0] = 265; s.binding.bridge_intid[1] = 266;
    s.binding.mip_intid_base = 160; s.binding.mip_intid_count = 64;
    for (unsigned i = 0; i < 4; i++) s.binding.intx_intid[i] = 261+i;
}
int main()
{
    BCM2712PCIePHYTransport s;
    bcm2712_phy_observation sentinel, out;
    std::memset(&sentinel,0xa5,sizeof(sentinel));
    fresh(s); out = sentinel;
    assert(s.runInitialPHY(&out));
    assert(s.phase == BCM2712_PHY_COMPLETE && s.irqClaimed && !s.claimingIRQ);
    assert(s.retains == 1 && watchdogClaims == 1 && threadReferences == 1 && interruptCalls == 2);
    assert(gicWrites == 3 && controllerIO == 7 && resetInits == 1 && daif == 0x200);
    assert(out.irq.typer == 15 && out.irq.enabled[0][2] == (UINT32_MAX ^ 0x7e0));
    const unsigned checks = watchdogChecks, providers = providerCalls;
    assert(!s.runInitialPHY(&out) && watchdogClaims == 1);
    for (unsigned n = 1; n <= checks; n++) {
        fresh(s); failWatchdog = n; out = sentinel;
        assert(!s.runInitialPHY(&out) && s.phase == BCM2712_PHY_FAILED);
        assert(!std::memcmp(&out,&sentinel,sizeof(out)) && watchdogClaims == 1 && s.retains == 1);
        assert(!s.runInitialPHY(&out) && watchdogClaims == 1);
        if (n <= 2) assert(!resetInits && !controllerIO && interruptCalls == 1 && daif == 0x3c0);
    }
    for (unsigned n = 1; n <= providers; n++) {
        fresh(s); failProvider = n; out = sentinel;
        assert(!s.runInitialPHY(&out) && s.phase == BCM2712_PHY_FAILED);
        assert(!std::memcmp(&out,&sentinel,sizeof(out)) && gicWrites == 3);
    }
    fresh(s,false); assert(s.runInitialPHY(&out) && daif == 0x3c0 && interruptCalls == 2);
    fresh(s); failClaim = true; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicReads && !gicWrites && !interruptCalls && !resetInits);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)));
    fresh(s); registers[0x314/4] = 1; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicWrites && !resetInits && !controllerIO && daif == 0x3c0);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)) && interruptCalls == 1);
    fresh(s); ignoreGICWrite = true; out = sentinel;
    assert(!s.runInitialPHY(&out) && gicWrites == 3 && !resetInits && !controllerIO && daif == 0x3c0);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)) && interruptCalls == 1);
    fresh(s); rpi5_gicd_base = 0; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicReads && !gicWrites && !resetInits && daif == 0x3c0);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)) && interruptCalls == 1);
    fresh(s); registers[1] = 7; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicWrites && !resetInits && daif == 0x3c0);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)) && interruptCalls == 1);
    fresh(s); restoreReenable = true; out = sentinel;
    assert(!s.runInitialPHY(&out) && !controllerIO && s.phase == BCM2712_PHY_FAILED);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)) && interruptCalls == 2);
    fresh(s); phyOwner = nullptr; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicReads && !gicWrites && !resetInits && !interruptCalls);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)));
    fresh(s); s.provider.opened = false; out = sentinel;
    assert(!s.runInitialPHY(&out) && !gicReads && !gicWrites && !resetInits && !interruptCalls);
    assert(!std::memcmp(&out,&sentinel,sizeof(out)));
    for (unsigned attack = 0; attack < 6; attack++) {
        fresh(s); out = sentinel;
        providerReenable = attack == 0; providerActive = attack == 1; providerMappingLoss = attack == 2;
        providerPhaseLoss = attack == 3; providerReentry = attack == 4; providerCloses = attack == 5;
        assert(!s.runInitialPHY(&out) && s.phase == BCM2712_PHY_FAILED && !controllerIO);
        assert(!std::memcmp(&out,&sentinel,sizeof(out)) && gicWrites == 3);
    }
    fresh(s); s.checkingLifecycle = true; out = sentinel;
    assert(!s.runInitialPHY(&out) && !watchdogClaims && !interruptCalls && !s.retains);
    fresh(s); thread = &other_thread_id;
    assert(!s.runInitialPHY(&out) && !watchdogClaims && !s.retains && !gicReads);
    fresh(s); interruptContext = true;
    assert(!s.runInitialPHY(&out) && !watchdogClaims && !s.retains);
    fresh(s); s.ownerThread = nullptr;
    assert(!s.runInitialPHY(&out) && !watchdogClaims && !s.retains);
    fresh(s); s.controllerMode = false; out = sentinel;
    assert(s.runInitialPHY(&out) && watchdogClaims == 1 && controllerIO == 7);
    assert(!gicReads && !gicWrites && !interruptCalls && !providerCalls && !threadReferences);
    fresh(s); assert(s.runInitialPHY(&out)); s.phase = BCM2712_PHY_LINK_TRAINING;
    thread = &other_thread_id; unsigned readsBefore = gicReads;
    assert(!s.guard() && s.phase == BCM2712_PHY_LINK_TRAINING && gicReads == readsBefore);
    thread = &thread_id;
    for (unsigned p : {unsigned(BCM2712_PHY_RESETTING), unsigned(BCM2712_PHY_CALIBRATING),
            unsigned(BCM2712_PHY_CONFIGURING), unsigned(BCM2712_PHY_UBUS_CONFIGURING),
            unsigned(BCM2712_PHY_UNUSED_INSPECTING), unsigned(BCM2712_PHY_QOS_CONFIGURING),
            unsigned(BCM2712_PHY_CLOCK_PREPARING), unsigned(BCM2712_PHY_RC_CONFIGURING),
            unsigned(BCM2712_PHY_LINK_TRAINING), unsigned(BCM2712_PHY_CLOCK_FINISHING)}) {
        s.phase = p; unsigned before = gicReads; unsigned wd = watchdogChecks;
        assert(s.guard() && gicReads == before+40 && watchdogChecks == wd+6 && gicWrites == 3);
    }
    registers[0x220/4] ^= UINT32_MAX; /* Pending changes are permitted, never cleared by transport. */
    assert(s.guard() && gicWrites == 3);
    registers[0x120/4] |= 0x20; readsBefore = controllerIO;
    assert(!s.guard() && s.phase == BCM2712_PHY_FAILED && controllerIO == readsBefore);
    std::printf("PCIE_IRQ_TRANSPORT_HOST_PASS ACTUAL_INITIAL_GUARD_PE_CORE=1 WATCHDOG_FAILURES=%u "
                "PROVIDER_FAILURES=%u RESTORE_SUCCESS_ONLY=1 NO_MMIO=1\n",checks,providers);
}
