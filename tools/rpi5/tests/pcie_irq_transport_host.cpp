int rpi5_pcie_reset_init(rpi5_pcie_reset *s, const rpi5_pcie_fdt *, const rpi5_pcie_reset_io *io)
{ resetInits++; s->io = *io; s->state = RPI5_PCIE_RESET_READY; return 0; }
int rpi5_pcie_reset_pulse(rpi5_pcie_reset *s, rpi5_pcie_reset_observation *out)
{
    uint32_t v;
    if (s->io.status(s->io.context,&v) || s->io.assert_bridge(s->io.context) ||
        s->io.deassert_bridge(s->io.context)) return -1;
    s->state = RPI5_PCIE_RESET_COMPLETE; *out = {}; return 0;
}
int rpi5_pcie_rescal_init(rpi5_pcie_rescal *s, const rpi5_pcie_fdt *, const rpi5_pcie_rescal_io *io)
{ s->io = *io; s->state = RPI5_PCIE_RESCAL_READY; return 0; }
int rpi5_pcie_rescal_calibrate(rpi5_pcie_rescal *s, rpi5_pcie_rescal_observation *out)
{
    uint32_t v;
    if (s->io.claim_shared(s->io.context) || s->io.read_start(s->io.context,&v) ||
        s->io.write_start(s->io.context,1)) return -1;
    s->state = RPI5_PCIE_RESCAL_COMPLETE; *out = {}; return 0;
}
int rpi5_pcie_serdes_init(rpi5_pcie_serdes *s, const rpi5_pcie_fdt *, const rpi5_pcie_mdio_io *io,
    const rpi5_pcie_rescal *, const rpi5_pcie_reset *)
{ s->mdio.io = *io; s->state = RPI5_PCIE_SERDES_READY; return 0; }
int rpi5_pcie_serdes_configure54(rpi5_pcie_serdes *s, rpi5_pcie_serdes_observation *out)
{
    if (s->mdio.io.write32(s->mdio.io.context,0x4304,0)) return -1;
    s->state = RPI5_PCIE_SERDES_COMPLETE; *out = {}; return 0;
}
