static bool ml_set_interrupts_enabled(bool enabled)
{
    /* Mirrors the real API's standard A/I/F mask invariant. */
    bool old = (daif & 0x1c0) != 0x1c0;
    assert((daif & 0x1c0) == 0 || (daif & 0x1c0) == 0x1c0);
    daif = enabled ? daif & ~UINT64_C(0x1c0) : daif | UINT64_C(0x1c0);
    interruptCalls++;
    if (enabled && restoreReenable) registers[0x120/4] |= 0x20;
    return old;
}
bool pe_rpi5_watchdog_claim_pcie(const void *owner, rpi5_pcie_watchdog_observation *out)
{
    watchdogClaims++;
    assert(watchdogClaims == 1 && owner && out && !watchdogOwner);
    if (failClaim) return false;
    watchdogOwner = owner; *out = {};
    return true;
}
bool pe_rpi5_watchdog_check_pcie(const void *owner)
{
    watchdogChecks++;
    return watchdogOwner == owner && watchdogChecks != failWatchdog;
}
static uint32_t rpi5_mmio_read32(vm_offset_t base, unsigned offset)
{
    assert(watchdogClaims == 1 && watchdogOwner && base == (uintptr_t)registers);
    assert(offset < sizeof(registers)); gicReads++;
    return registers[offset/4];
}
static void rpi5_mmio_write32(vm_offset_t base, unsigned offset, uint32_t value)
{
    assert(watchdogClaims == 1 && watchdogOwner && (daif & 0x1c0) == 0x1c0);
    assert(base == (uintptr_t)registers && !resetInits && !controllerIO);
    assert((offset == 0x194 || offset == 0x198) ? value == UINT32_MAX : offset == 0x1a0 && value == 0x7e0);
    gicWrites++;
    if (!ignoreGICWrite) registers[(offset-0x80)/4] &= ~value;
}
