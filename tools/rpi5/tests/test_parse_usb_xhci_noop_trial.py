class USBXHCINoopParserTests(unittest.TestCase):
    def test_native_usb_records_pass_without_removed_gem_records(self):
        result = parser.parse(TRANSCRIPT, MARKER)
        self.assertEqual(result["status"], "pass")
        self.assertEqual(result["noop"]["PSC"], 1)
        self.assertEqual(result["watchdog_checks"], 68420)
        self.assertTrue(result["bme_restored"])

    def test_completion_cleanup_and_bounds_mutations_fail(self):
        mutations = (
            ("CURRENT=0002", "CURRENT=0006"),
            ("DMA_CHECKS=7", "DMA_CHECKS=6"),
            ("PSC=1", "PSC=9"),
            ("CHECKS=68420", "CHECKS=65536"),
            ("UNMAPPED=03", "UNMAPPED=01"),
            ("END OK=1", "END OK=0"),
        )
        for old, new in mutations:
            with self.subTest(field=old):
                with self.assertRaises(ValueError):
                    parser.parse(TRANSCRIPT.replace(old, new, 1), MARKER)


