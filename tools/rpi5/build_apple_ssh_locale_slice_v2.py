"""Preserve first include-failure audit; apply actual Apple build headers.

The FreeBSD compatibility header and __LIBC__ are original build settings,
not alternate locale/pthread implementations. Features are generated by the
unchanged Apple generator. collate.c additionally receives sys/param.h for
its otherwise undeclared MAX macro; no original translation unit is edited.
"""
import os
from pathlib import Path
import types
from tools.rpi5 import build_apple_ssh_locale_slice as old


def implementation():
    text = Path(old.__file__).read_text()
    edits = [
        ('import json\n', 'import json\nimport os\n'),
        ('for path in (Path(__file__).resolve(), original_start,',
         'for path in (Path(__file__).resolve(), ORIGINAL_BUILDER, original_start,\n'
         "                 LIBC/'xcodescripts/generate_features.pl',\n"
         "                 LIBC/'Platforms/macosx/Makefile.inc',"),
        ('def run(args,label):', 'def run(args,label,env=None):'),
        ('capture_output=True,timeout=90)', 'capture_output=True,timeout=90,env=env)'),
        ('commands.append(dict(command=args,cwd=str(ROOT),returncode=result.returncode,',
         'commands.append(dict(command=args,cwd=str(ROOT),returncode=result.returncode,\n'
         '            explicit_environment=env,'),
        ("    flags = old[:old.index('-MD')]\n",
         "    features = out/'derived'\n"
         "    environment = dict(ARCHS='arm64', VARIANT_PLATFORM_NAME='macosx',\n"
         "                       SRCROOT=str(LIBC), DERIVED_FILES_DIR=str(features))\n"
         "    generated = run(['/usr/bin/perl', LIBC/'xcodescripts/generate_features.pl'],\n"
         "                    'original-features', environment)\n"
         "    if generated.returncode: raise ValueError('Original feature generation failed')\n"
         "    flags = old[:old.index('-MD')]\n"
         "    i = flags.index('-idirafter'); del flags[i:i+2]\n"
         "    flags += ['-D__LIBC__=1', '-D__DARWIN_UNIX03=1',\n"
         "              '-D__DARWIN_64_BIT_INO_T=1', '-D__DARWIN_VERS_1050=1',\n"
         "              '-D__DARWIN_NON_CANCELABLE=1']\n"
         "    for path in (LIBC/'include', LIBC/'stdtime/FreeBSD', features/'arm64',\n"
         "                 ROOT/'build/rpi5/apple-pthread-bcm2712-qualified-x9kp1ral/include',\n"
         "                 ROOT/'build/rpi5/apple-libplatform-main-candidate-20261013/private',\n"
         "                 ROOT/'build/rpi5/apple-libplatform-main-candidate-20261013/include',\n"
         "                 ROOT/'libkern'):\n"
         "        flags += ['-I',str(path)]\n"),
        ("        compile(flags,LIBC/name,'target-'+Path(name).stem)",
         "        unit_flags = list(flags)\n"
         "        if '/FreeBSD/' in name:\n"
         "            unit_flags += ['-include',str(LIBC/'fbsdcompat/_fbsd_compat_.h')]\n"
         "        if name == 'locale/FreeBSD/collate.c':\n"
         "            unit_flags += ['-include','sys/param.h']\n"
         "        compile(unit_flags,LIBC/name,'target-'+Path(name).stem)"),
        ("profile='original-apple-current-strtoll-xlocale-slice-v1'",
         "profile='original-apple-current-strtoll-xlocale-slice-v2'"),
        ('for p in out.iterdir() if p.is_file()', 'for p in out.rglob("*") if p.is_file()'),
    ]
    for before, after in edits:
        if text.count(before) != 1:
            raise ValueError('Exact initial audit shape differs: '+before)
        text = text.replace(before,after)
    module = types.ModuleType('_isolated_apple_locale_v2')
    module.__file__ = __file__
    module.ORIGINAL_BUILDER = Path(old.__file__).resolve()
    exec(compile(text,old.__file__,'exec'),module.__dict__)
    return module


if __name__ == '__main__':
    implementation().build()
